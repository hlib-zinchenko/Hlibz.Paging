using System.Collections.Immutable;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hlibz.Paging.Generators;

/// <summary>
/// Lists every sortable DTO of the assembly being compiled (a class or struct, not abstract or
/// generic, with a <c>[Sortable]</c> property of its own or inherited) in a generated
/// <c>SortableDtoManifestAttribute</c> applied to the assembly, which
/// <c>SortableDto.ValidateAll</c> reads instead of scanning types at runtime. Invalid DTOs are
/// listed too, so the runtime check still names them where <c>HPAG001</c> is suppressed. A DTO
/// the generated code can't reach (private, or nested in a private type) is left out; the
/// analyzer still checks it.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SortableDtoManifestGenerator : IIncrementalGenerator
{
    private const string ManifestAttributeName = "Hlibz.Paging.SortableDtoManifestAttribute";

    private const string Namespace = "Hlibz.Paging.Generated";

    private static readonly SymbolDisplayFormat TypeOfFormat =
        SymbolDisplayFormat.FullyQualifiedFormat;

    private static string GeneratorName => typeof(SortableDtoManifestGenerator).Assembly.GetName().Name;

    private static string GeneratorVersion =>
        typeof(SortableDtoManifestGenerator).Assembly.GetName().Version?.ToString() ?? "0.0.0.0";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<string> dtos = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax,
                static (syntaxContext, cancellationToken) => DtoName(syntaxContext, cancellationToken))
            .Where(static name => name is not null)
            .Select(static (name, _) => name!);

        IncrementalValueProvider<string?> manifestClassName = context.CompilationProvider
            .Select(static (compilation, _) => ClassNameFor(compilation));

        context.RegisterSourceOutput(
            dtos.Collect().Combine(manifestClassName),
            static (sourceContext, input) => Emit(sourceContext, input.Left, input.Right));
    }

    private static string? DtoName(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        Compilation compilation = context.SemanticModel.Compilation;
        if (context.SemanticModel.GetDeclaredSymbol(context.Node, cancellationToken) is not INamedTypeSymbol type
            || !SortableDtoSymbols.IsCandidate(type)
            || compilation.GetTypeByMetadataName(SortableDtoSymbols.SortableAttributeName) is not { } sortable
            || !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
            || IsPrivateOrNestedInPrivate(type)
            || SortableDtoSymbols.Count(type, sortable).Sortable == 0)
        {
            return null;
        }

        return type.ToDisplayString(TypeOfFormat);
    }

    /// <summary>
    /// Whether code outside the type's containing types can't name it: a private or protected
    /// nested type, or one nested in such a type.
    /// </summary>
    private static bool IsPrivateOrNestedInPrivate(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
        {
            if (current.DeclaredAccessibility is Accessibility.Private
                or Accessibility.Protected
                or Accessibility.ProtectedAndInternal)
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// The manifest class's name for the assembly being compiled, unique to it so assemblies that
    /// see each other's internals don't clash, or <see langword="null"/> when the compilation
    /// doesn't reference Hlibz.Paging (nothing to generate).
    /// </summary>
    private static string? ClassNameFor(Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(ManifestAttributeName) is null)
        {
            return null;
        }

        StringBuilder name = new("SortableDtoManifest_");
        foreach (char character in compilation.AssemblyName ?? "Assembly")
        {
            name.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return name.ToString();
    }

    private static void Emit(
        SourceProductionContext context,
        ImmutableArray<string> dtos,
        string? className)
    {
        if (className is null)
        {
            return;
        }

        StringBuilder source = new();
        source.Append(
            $$"""
            // <auto-generated/>
            #nullable enable
            // Obsolete DTOs are still checked.
            #pragma warning disable CS0612, CS0618

            [assembly: global::{{Namespace}}.{{className}}]

            namespace {{Namespace}}
            {
                /// <summary>
                /// The sortable DTOs the Hlibz.Paging source generator found in this assembly, read
                /// by SortableDto.ValidateAll.
                /// </summary>
                [global::System.CodeDom.Compiler.GeneratedCode("{{GeneratorName}}", "{{GeneratorVersion}}")]
                internal sealed class {{className}} : global::{{ManifestAttributeName}}
                {
                    private static readonly global::System.Func<global::Hlibz.Paging.SortableDto>[] All =
                    {

            """);

        // A partial DTO is found once per declaration; list it once, in declaration order.
        HashSet<string> seen = new(StringComparer.Ordinal);
        foreach (string dto in dtos.Where(seen.Add))
        {
            source.Append(
                $$"""
                            static () => global::Hlibz.Paging.SortableDto.For<{{dto}}>(),

                """);
        }

        source.Append(
            """
                    };

                    /// <inheritdoc/>
                    public override global::System.Collections.Generic.IReadOnlyList<global::System.Func<global::Hlibz.Paging.SortableDto>> Dtos => All;
                }
            }

            """);
        context.AddSource("SortableDtoManifest.g.cs", source.ToString());
    }
}
